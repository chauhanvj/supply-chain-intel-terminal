def seed_order_pipeline_db():
    conn = get_db()
    cursor = conn.cursor()

    # Clear existing rows to allow idempotent re-seeding
    cursor.execute("DELETE FROM significant_orders")
    cursor.execute("DELETE FROM order_book_companies")

    for c in COMPANIES_DATA:
        cursor.execute("""
            INSERT INTO order_book_companies (
                id, ticker, exchange, company_name, market_cap_tier, market_cap_inr_cr,
                sector, industry, total_order_book_cr, ttm_revenue_cr, book_to_bill_ratio,
                recent_order_inflows_cr, historical_avg_order_size_cr, recent_avg_order_size_cr,
                surge_multiplier, bidding_pipeline_cr, delivery_timeline_months, execution_risk_level,
                primary_material_bottleneck, material_lead_time_weeks, order_surge_thesis, last_updated
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            c["id"], c["ticker"], c["exchange"], c["company_name"], c["market_cap_tier"], c["market_cap_inr_cr"],
            c["sector"], c["industry"], c["total_order_book_cr"], c["ttm_revenue_cr"], c["book_to_bill_ratio"],
            c["recent_order_inflows_cr"], c["historical_avg_order_size_cr"], c["recent_avg_order_size_cr"],
            c["surge_multiplier"], c["bidding_pipeline_cr"], c["delivery_timeline_months"], c["execution_risk_level"],
            c["primary_material_bottleneck"], c["material_lead_time_weeks"], c["order_surge_thesis"], c["last_updated"]
        ))

    for o in ORDERS_DATA:
        cursor.execute("""
            INSERT INTO significant_orders (
                id, company_id, ticker, company_name, client_name, client_category,
                order_value_cr, announcement_date, scope_of_work, execution_period_months,
                historical_avg_benchmark_cr, surge_factor, order_significance_tag,
                pct_of_annual_revenue, critical_raw_materials, bottleneck_impact_note, status
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            o["id"], o["company_id"], o["ticker"], o["company_name"], o["client_name"], o["client_category"],
            o["order_value_cr"], o["announcement_date"], o["scope_of_work"], o["execution_period_months"],
            o["historical_avg_benchmark_cr"], o["surge_factor"], o["order_significance_tag"],
            o["pct_of_annual_revenue"], o["critical_raw_materials"], o["bottleneck_impact_note"], o["status"]
        ))

    conn.commit()
    conn.close()
    print(f"Successfully seeded {len(COMPANIES_DATA)} order book companies and {len(ORDERS_DATA)} landmark orders.")

if __name__ == "__main__":
    seed_order_pipeline_db()
